import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createEntryClient } from '../src/client/model.js';
import { createEntryViews } from '../src/client/view.js';
import { entryFactory } from '../src/client/entry.js';

// These three self-contained functions form a single lazy module-loader artifact.
// No source evaluation, dependency bundling, minifier, network, or global tooling.
const dictionaries = {};
for (const language of ['en', 'zh']) {
  dictionaries[language] = JSON.parse(await readFile(new URL(`../locale/${language}.json`, import.meta.url), 'utf8')).ui;
}
const output = `// Generated by scripts/build.mjs. Do not edit.\nwindow.__ModuleLoader__.load({\n  id: '@wangzf/dsh-openai-codex-oauth',\n  factory(require) {\n    const createEntryClient = ${createEntryClient.toString()};\n    const createEntryViews = ${createEntryViews.toString()};\n    const entryFactory = ${entryFactory.toString()};\n    return entryFactory(require, createEntryClient, createEntryViews, ${JSON.stringify(dictionaries)});\n  }\n});\n`;
await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
await writeFile(new URL('../dist/client.js', import.meta.url), output);
console.log('Built single Client module; React supplied by Harness.');
